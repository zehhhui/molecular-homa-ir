#!/usr/bin/env python3
"""Decompose frozen mol-HOMA-IR treatment contrasts into molecular contributions.

Inputs are generated by extract_contributions.R. Treatment effects are estimated
within each trial, without ancestry PCs or BMI-change adjustment. The lowering
denominator includes every feature, before stability and direction filtering.
"""
from __future__ import annotations

import os

# Preserve the numerical implementation used in the manuscript analysis.
for _key in ("OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS", "MKL_NUM_THREADS",
             "VECLIB_MAXIMUM_THREADS"):
    os.environ[_key] = "1"

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import t

TRIALS = {"CMAP": ("PB", 202610031), "CMAS": ("SP", 202610032)}
TOLERANCE = 1e-12


def female_indicator(sex: pd.Series) -> np.ndarray:
    """The analysis codes sex 1=male, 2=female; textual equivalents are accepted."""
    values = sex.astype(str).str.strip().str.lower()
    mapping = {"1": 0.0, "1.0": 0.0, "male": 0.0, "m": 0.0,
               "2": 1.0, "2.0": 1.0, "female": 1.0, "f": 1.0}
    converted = values.map(mapping)
    if converted.isna().any():
        raise ValueError("sex must use 1=male/2=female or male/female labels")
    return converted.to_numpy(dtype=float)


def build_design(participants: pd.DataFrame, control: str) -> pd.DataFrame:
    """Construct the original no-PC ANCOVA design, using CG32 as reference."""
    required = {"arm", "sex", "age", "baseline_mol"}
    if not required.issubset(participants):
        raise ValueError(f"Missing design fields: {sorted(required-set(participants))}")
    arms = participants.arm.astype(str)
    expected = {"CG32", "CG48", control}
    if set(arms) != expected:
        raise ValueError(f"Each trial must contain exactly these arms: {sorted(expected)}")
    age = participants.age.to_numpy(dtype=float)
    age_sd = age.std(ddof=1)
    if not np.isfinite(age_sd) or age_sd <= 0:
        raise ValueError("Age must vary within each trial")
    result = pd.DataFrame({
        "Intercept": np.ones(len(participants)),
        "ArmCG48": arms.eq("CG48").to_numpy(dtype=float),
        "Arm" + control: arms.eq(control).to_numpy(dtype=float),
        "baseline": participants.baseline_mol.to_numpy(dtype=float),
        "Sex2": female_indicator(participants.sex),
        "Age": (age - age.mean()) / age_sd,
    }, index=participants.index)
    if not np.isfinite(result.to_numpy()).all():
        raise ValueError("The ANCOVA design contains nonfinite values")
    if np.linalg.matrix_rank(result.to_numpy()) != result.shape[1]:
        raise ValueError("ANCOVA design is rank deficient; inspect baseline, sex and age variation")
    if len(result) <= result.shape[1]:
        raise ValueError("Insufficient residual degrees of freedom")
    return result


def contrast_matrix(columns, control: str) -> np.ndarray:
    """Rows are CG32-control and CG48-control, respectively."""
    names = list(columns)
    result = np.zeros((2, len(names)))
    result[:, names.index("Arm" + control)] = -1
    result[1, names.index("ArmCG48")] = 1
    return result


def fit_contrasts(X, Y, C) -> dict:
    """OLS treatment contrasts and ordinary t-based 95% confidence intervals."""
    X, Y, C = map(lambda a: np.asarray(a, dtype=float), (X, Y, C))
    if Y.ndim == 1:
        Y = Y[:, None]
    if X.ndim != 2 or Y.ndim != 2 or len(X) != len(Y):
        raise ValueError("X and Y must be aligned two-dimensional matrices")
    df = len(X) - X.shape[1]
    if df <= 0 or np.linalg.matrix_rank(X) != X.shape[1]:
        raise ValueError("Full-rank design and positive residual degrees of freedom required")
    inverse = np.linalg.inv(X.T @ X)
    coefficients = np.linalg.solve(X.T @ X, X.T @ Y)
    effect = C @ coefficients
    residual = Y - X @ coefficients
    variance = np.sum(residual**2, axis=0) / df
    se = np.sqrt(np.maximum(np.diag(C @ inverse @ C.T)[:, None] * variance, 0))
    critical = t.ppf(0.975, df)
    return dict(coefficients=coefficients, effect=effect, se=se, df=df,
                ci_lower=effect-critical*se, ci_upper=effect+critical*se,
                inverse=inverse, residual_variance=variance)


def lowering_shares(effects) -> np.ndarray:
    """Share of gross lowering across ALL supplied feature columns, not net effect."""
    values = np.asarray(effects, dtype=float)
    if not np.isfinite(values).all():
        raise ValueError("Contribution effects must be finite")
    downward = np.maximum(-values, 0)
    denominator = downward.sum(axis=-1, keepdims=True)
    if (denominator <= 0).any():
        raise ValueError("A contrast has no lowering contribution; its lowering shares are undefined")
    return 100 * downward / denominator


# Short alias retained for direct comparison with the original implementation.
shares = lowering_shares


def bootstrap_contrasts(X, Y, arms, control: str, n_boot: int, seed: int) -> dict:
    """Arm-stratified participant bootstrap, conditional on the frozen models.

    The batch size and RNG draw order reproduce the original analysis. All
    molecules are resampled together. Singular bootstrap designs are reported
    rather than silently replacing OLS with a different estimator.
    """
    if n_boot < 2:
        raise ValueError("At least two bootstrap replicates are required")
    if isinstance(X, pd.DataFrame):
        columns = list(X.columns)
    else:
        columns = ["Intercept", "ArmCG48", "Arm"+control, "baseline", "Sex2", "Age"]
    X, Y = np.asarray(X, dtype=float), np.asarray(Y, dtype=float)
    arms = np.asarray(arms, dtype=str)
    C = contrast_matrix(columns, control)
    if len(X) != len(Y) or len(X) != len(arms):
        raise ValueError("Bootstrap input rows are not aligned")
    active = np.any(Y != 0, axis=0)
    Ya = Y[:, active]
    rng = np.random.default_rng(seed)
    boot_effect = np.zeros((n_boot, 2, Y.shape[1]))
    for start in range(0, n_boot, 50):
        count = min(50, n_boot-start)
        W = np.zeros((count, len(X)))
        for arm in ("CG32", "CG48", control):
            ix = np.flatnonzero(arms == arm)
            if len(ix) == 0:
                raise ValueError(f"No participants in arm {arm}")
            W[:, ix] = rng.multinomial(len(ix), np.full(len(ix), 1/len(ix)), size=count)
        gram = np.einsum("ni,bn,nj->bij", X, W, X, optimize=True)
        xty = np.einsum("ni,bn,nk->bik", X, W, Ya, optimize=True)
        try:
            coefficients = np.linalg.solve(gram, xty)
        except np.linalg.LinAlgError as exc:
            raise ValueError("Singular bootstrap ANCOVA design; use a sufficiently large, "
                             "variable sample rather than changing the estimator silently") from exc
        boot_effect[start:start+count, :, active] = np.einsum("cp,bpk->bck", C, coefficients)
    boot_share = lowering_shares(boot_effect)
    lower, upper = np.quantile(boot_share, [0.025, 0.975], axis=0)
    return dict(effects=boot_effect, shares=boot_share,
                se=boot_share.std(axis=0, ddof=1), ci_lower=lower, ci_upper=upper)


def eligible_features(selection: pd.DataFrame, min_folds: int = 1) -> pd.DataFrame:
    """Require at least min_folds nonzero coefficients in EVERY repetition."""
    required = {"feature_id", "repetition", "n_selected", "n_folds"}
    if not required.issubset(selection):
        raise ValueError(f"Missing selection columns: {sorted(required-set(selection))}")
    s = selection.copy()
    if s.duplicated(["feature_id", "repetition"]).any():
        raise ValueError("Selection records must be unique per feature and repetition")
    if len(s) == 0:
        raise ValueError("Selection table is empty")
    for field in ("n_selected", "n_folds"):
        values = pd.to_numeric(s[field], errors="raise")
        if not np.isfinite(values).all() or (values != np.floor(values)).any():
            raise ValueError("Selection counts must be finite integers")
        s[field] = values.astype(int)
    if s.n_folds.nunique() != 1 or s.n_folds.iloc[0] < 2:
        raise ValueError("A consistent number of outer folds is required")
    n_folds = int(s.n_folds.iloc[0])
    if not 1 <= min_folds <= n_folds:
        raise ValueError("min_folds must lie between 1 and the outer fold count")
    if ((s.n_selected < 0) | (s.n_selected > s.n_folds)).any():
        raise ValueError("Invalid within-repetition selected-fold count")
    repetitions = s.repetition.nunique()
    result = s.groupby("feature_id", sort=False).agg(
        n_repetitions=("repetition", "nunique"),
        min_folds_per_repetition=("n_selected", "min"),
        n_selected=("n_selected", "sum"),
    ).reset_index()
    if not result.n_repetitions.eq(repetitions).all():
        raise ValueError("Missing feature-by-repetition records; absence is not evidence of selection")
    result["n_folds"] = n_folds
    result["eligible"] = result.min_folds_per_repetition.ge(min_folds)
    return result


def adjusted_arm_means(X: pd.DataFrame, Z, arms, control: str) -> list[dict]:
    """Counterfactual-arm standardized means of frozen feature-SD changes."""
    matrix = X.to_numpy(dtype=float)
    Z = np.asarray(Z, dtype=float)
    fitted = fit_contrasts(matrix, Z, contrast_matrix(X.columns, control))
    result = []
    for arm in ("CG32", "CG48", control):
        counterfactual = X.copy()
        counterfactual["ArmCG48"] = float(arm == "CG48")
        counterfactual["Arm"+control] = float(arm == control)
        L = counterfactual.mean(axis=0).to_numpy()
        means = L @ fitted["coefficients"]
        se = np.sqrt(np.maximum((L @ fitted["inverse"] @ L) * fitted["residual_variance"], 0))
        result.append(dict(arm=arm, n=int(np.sum(np.asarray(arms) == arm)), mean=means, se=se))
    return result


def read_matrix(path: Path) -> pd.DataFrame:
    frame = pd.read_csv(path, dtype={"sample_id": str})
    if "sample_id" not in frame or frame.sample_id.duplicated().any():
        raise ValueError(f"{path.name} must contain unique sample_id values")
    result = frame.set_index("sample_id")
    if result.columns.duplicated().any() or not np.isfinite(result.to_numpy(dtype=float)).all():
        raise ValueError(f"{path.name} has duplicate columns or nonfinite molecular data")
    return result


def run(input_dir: Path, output_dir: Path, n_boot: int = 2000,
        min_folds: int = 1, top_n: int = 10, save_bootstrap: bool = False) -> dict:
    input_dir, output_dir = Path(input_dir), Path(output_dir)
    if n_boot == 1 or n_boot < 0:
        raise ValueError("bootstrap must be 0 (point estimates only) or at least 2")
    if top_n < 1:
        raise ValueError("top_n must be positive")
    filenames = ["participant_contributions.csv", "participant_molecular_changes.csv",
                 "participant_scores_covariates.csv", "feature_annotations.csv", "selection_by_repeat.csv"]
    contribution = read_matrix(input_dir/filenames[0])
    change = read_matrix(input_dir/filenames[1])
    participants = pd.read_csv(input_dir/filenames[2], dtype={"sample_id": str})
    annotations = pd.read_csv(input_dir/filenames[3], dtype={"feature_id": str})
    selection = pd.read_csv(input_dir/filenames[4], dtype={"feature_id": str})
    fields = {"sample_id", "trial", "arm", "sex", "age", "baseline_mol", "followup_mol"}
    if not fields.issubset(participants) or participants.sample_id.duplicated().any():
        raise ValueError("Participant file lacks required fields or contains duplicate sample_id values")
    if not {"feature_id", "label", "omics"}.issubset(annotations) or annotations.feature_id.duplicated().any():
        raise ValueError("Feature annotation requires unique feature_id, label and omics")
    feature_ids = list(contribution.columns)
    if set(annotations.feature_id) != set(feature_ids) or set(change.columns) != set(feature_ids):
        raise ValueError("Contribution, standardized-change and annotation feature sets must match exactly")
    annotations = annotations.set_index("feature_id").loc[feature_ids]
    change = change.loc[:, feature_ids]
    eligibility = eligible_features(selection, min_folds)
    if set(eligibility.feature_id) != set(feature_ids):
        raise ValueError("Selection table must cover every candidate feature, including zeros")
    unknown = set(participants.trial.dropna().astype(str)) - set(TRIALS)
    if unknown:
        raise ValueError(f"Unexpected trial names: {sorted(unknown)}")
    source_n = len(participants)
    for col in ("age", "baseline_mol", "followup_mol"):
        participants[col] = pd.to_numeric(participants[col], errors="coerce")
    complete = participants[list(fields)].notna().all(axis=1)
    complete &= np.isfinite(participants[["age", "baseline_mol", "followup_mol"]]).all(axis=1)
    participants = participants.loc[complete].copy()
    if not set(participants.sample_id).issubset(contribution.index) or not set(participants.sample_id).issubset(change.index):
        raise ValueError("Molecular matrices do not contain every eligible participant")
    output_dir.mkdir(parents=True, exist_ok=True)
    eligibility.merge(annotations.reset_index(), on="feature_id", validate="one_to_one").to_csv(
        output_dir/"feature_selection_audit.csv", index=False)
    eligible = set(eligibility.loc[eligibility.eligible, "feature_id"])
    eligible_table = eligibility.loc[eligibility.eligible].merge(annotations.reset_index(), on="feature_id")
    eligible_table.to_csv(output_dir/"eligible_features.csv", index=False)

    all_rows, totals, audits, ranked_rows, filter_rows, heatmap_rows = [], [], [], [], [], []
    active = contribution.ne(0).any(axis=0).to_numpy()
    for trial, (control, seed) in TRIALS.items():
        d = participants.loc[participants.trial.eq(trial)].copy()
        if d.empty:
            continue
        # Preserve input participant order so seeded bootstrap draws are reproducible.
        X = build_design(d, control)
        C = contrast_matrix(X.columns, control)
        Y = contribution.loc[d.sample_id, feature_ids].to_numpy(dtype=float)
        Z = change.loc[d.sample_id, feature_ids].to_numpy(dtype=float)
        delta = d.followup_mol.to_numpy()-d.baseline_mol.to_numpy()
        np.testing.assert_allclose(Y.sum(axis=1), delta, atol=TOLERANCE, rtol=TOLERANCE,
                                   err_msg="Molecular contributions do not reconstruct score changes")
        fit = fit_contrasts(X, Y, C)
        total = fit_contrasts(X, d.followup_mol.to_numpy(), C)["effect"].ravel()
        effect = fit["effect"]
        np.testing.assert_allclose(effect.sum(axis=1), total, atol=TOLERANCE, rtol=TOLERANCE,
                                   err_msg="Molecular treatment effects do not reconstruct total score effects")
        share = lowering_shares(effect)
        average_share = share.mean(axis=0)
        if n_boot:
            boot = bootstrap_contrasts(X, Y, d.arm, control, n_boot, seed)
            if save_bootstrap:
                np.savez_compressed(output_dir/f"{trial}_bootstrap_contributions.npz",
                                    feature_ids=np.asarray(feature_ids, dtype=str),
                                    effects=boot["effects"], shares=boot["shares"], seed=seed)
        else:
            boot = {key: np.full_like(share, np.nan) for key in ("se", "ci_lower", "ci_upper")}
        qualifying = np.array([f in eligible for f in feature_ids]) & (effect < -TOLERANCE).all(axis=0)
        selected = np.flatnonzero(qualifying)
        # Original 141 groupby sorts feature IDs before ranking. This provides a
        # stable, deterministic tie rule while leaving distinct share ranks intact.
        chosen = sorted(selected, key=lambda j: (-average_share[j], feature_ids[j]))
        ranks = {j: rank for rank, j in enumerate(chosen, 1)}
        for j, feature in enumerate(feature_ids):
            annotation = annotations.loc[feature]
            if feature in eligible:
                filter_rows.append(dict(trial=trial, feature_id=feature, label=annotation.label,
                                        omics=annotation.omics, CG32_effect=effect[0, j],
                                        CG48_effect=effect[1, j], qualifying=bool(qualifying[j])))
            if qualifying[j]:
                ranked_rows.append(dict(trial=trial, rank=ranks[j], feature_id=feature,
                                        label=annotation.label, omics=annotation.omics,
                                        mean_share_across_two_doses_pct=average_share[j]))
            for dose, arm in enumerate(("CG32", "CG48")):
                all_rows.append(dict(trial=trial, arm=arm, control=control, feature_id=feature,
                    label=annotation.label, omics=annotation.omics, n=len(d),
                    effect_log=effect[dose, j], effect_SE=fit["se"][dose, j],
                    effect_CI95_lower=fit["ci_lower"][dose, j], effect_CI95_upper=fit["ci_upper"][dose, j],
                    lowering_share_pct=share[dose, j], share_bootstrap_SE=boot["se"][dose, j],
                    share_bootstrap_CI95_lower=boot["ci_lower"][dose, j],
                    share_bootstrap_CI95_upper=boot["ci_upper"][dose, j],
                    average_dose_lowering_share_pct=average_share[j],
                    direction=("lowering" if effect[dose, j] < -TOLERANCE else
                               "offsetting" if effect[dose, j] > TOLERANCE else "zero"),
                    nonzero_contribution_observed=bool(active[j]),
                    eligible_every_repetition=feature in eligible,
                    qualifying_both_doses=bool(qualifying[j])))
        for dose, arm in enumerate(("CG32", "CG48")):
            totals.append(dict(trial=trial, comparison=f"{arm} vs {control}", n=len(d),
                               total_score_effect=total[dose], sum_molecular_effect=effect[dose].sum(),
                               lowering_magnitude=-effect[dose, effect[dose] < 0].sum(),
                               offsetting_magnitude=effect[dose, effect[dose] > 0].sum(),
                               displayed_top_n=top_n,
                               displayed_lowering_share_pct=share[dose, chosen[:top_n]].sum()))
        for adjusted in adjusted_arm_means(X, Z, d.arm, control):
            for j in chosen:
                a = annotations.iloc[j]
                heatmap_rows.append(dict(trial=trial, rank=ranks[j], feature_id=feature_ids[j],
                                         label=a.label, omics=a.omics, arm=adjusted["arm"],
                                         n=adjusted["n"], adjusted_mean=adjusted["mean"][j],
                                         SE=adjusted["se"][j]))
        audits.append(dict(trial=trial, n=len(d), n_candidates=len(feature_ids),
                           n_active=int(active.sum()), n_eligible=len(eligible),
                           n_qualifying=len(chosen), participant_sum_error=float(np.max(abs(Y.sum(axis=1)-delta))),
                           treatment_sum_error=float(np.max(abs(effect.sum(axis=1)-total))),
                           share_sum_error=float(np.max(abs(share.sum(axis=1)-100))),
                           bootstrap_replicates=n_boot, bootstrap_seed=seed))
        print(f"{trial}: n={len(d)}; {len(chosen)} qualifying features", flush=True)

    if not audits:
        raise ValueError("No eligible trial population")
    all_results = pd.DataFrame(all_rows)
    ranked = pd.DataFrame(ranked_rows, columns=["trial", "rank", "feature_id", "label", "omics",
                                               "mean_share_across_two_doses_pct"])
    ranked = ranked.sort_values(["trial", "rank"])
    all_results.to_csv(output_dir/"all_molecular_contributions.csv", index=False)
    pd.DataFrame(totals).to_csv(output_dir/"total_effect_decomposition.csv", index=False)
    pd.DataFrame(audits).to_csv(output_dir/"decomposition_audit.csv", index=False)
    ranked.to_csv(output_dir/"ranked_contributors.csv", index=False)
    pd.DataFrame(filter_rows).to_csv(output_dir/"trial_specific_filter_audit.csv", index=False)
    heatmap_columns = ["trial", "rank", "feature_id", "label", "omics", "arm", "n", "adjusted_mean", "SE"]
    pd.DataFrame(heatmap_rows, columns=heatmap_columns).to_csv(output_dir/"heatmap_adjusted_molecular_changes.csv", index=False)
    displayed = ranked.loc[ranked["rank"].le(top_n)]
    displayed.to_csv(output_dir/"displayed_features.csv", index=False)
    all_results.merge(displayed[["trial", "feature_id", "rank"]], on=["trial", "feature_id"],
                      validate="many_to_one").to_csv(output_dir/"displayed_contributions.csv", index=False)
    # Shared means direction-qualified in every trial analyzed, not merely selected.
    analyzed_trials = [a["trial"] for a in audits]
    shared_ids = set(feature_ids)
    for trial in analyzed_trials:
        shared_ids &= set(ranked.loc[ranked.trial.eq(trial), "feature_id"])
    shared = annotations.loc[[f for f in feature_ids if f in shared_ids]].reset_index()
    shared.to_csv(output_dir/"shared_contributors.csv", index=False)
    settings = dict(
        score="Frozen baseline outer-held-out mol-HOMA-IR; repeated predictions averaged on log scale",
        design="Within trial: molecular contribution ~ Arm + baseline mol-HOMA-IR + sex + age",
        age_scaling="Within-trial sample mean and sample standard deviation (ddof=1)",
        ancestry_PC_adjustment=False, BMI_adjustment=False, BMI_change_adjustment=False,
        source_n=source_n, complete_case_n=len(participants), excluded_missing_covariates=source_n-len(participants),
        eligible_features=len(eligible), eligible_counts_by_omics=eligible_table.omics.value_counts().to_dict(),
        min_selected_folds_in_every_repetition=min_folds,
        rank="Descending mean of CG32/control and CG48/control gross-lowering shares within trial",
        denominator="All candidate molecules with negative adjusted treatment-minus-control contribution, before eligibility/direction/display filtering",
        direction_threshold=-TOLERANCE, significance_filter=False, p_values_used_for_selection=False,
        trial_counts={trial: ranked.loc[ranked.trial.eq(trial)].omics.value_counts().to_dict() for trial in analyzed_trials},
        shared_features=len(shared), shared_counts_by_omics=shared.omics.value_counts().to_dict(),
        displayed_top_n=top_n, bootstrap_replicates=n_boot,
        bootstrap="Participants resampled within trial and arm; frozen model coefficients; ANCOVAs and all-feature percentages recalculated each replicate",
        bootstrap_batch_size=50, bootstrap_seeds={trial: TRIALS[trial][1] for trial in analyzed_trials},
        error_bar="Bootstrap standard error of lowering percentage (ddof=1); percentile 95% interval also exported",
        uncertainty="Conditional on frozen molecular models and fixed feature selection/ranking; model-training and selection uncertainty not propagated",
        point_estimates_only=n_boot == 0,
    )
    (output_dir/"analysis_settings.json").write_text(json.dumps(settings, indent=2)+"\n")
    hashes = {name: hashlib.sha256((input_dir/name).read_bytes()).hexdigest() for name in filenames}
    (output_dir/"source_sha256.json").write_text(json.dumps(hashes, indent=2)+"\n")
    return settings


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True, help="Output directory from extract_contributions.R")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--bootstrap", type=int, default=2000, help="0 for point-estimate audit only; manuscript uses 2000")
    parser.add_argument("--min-folds", type=int, default=1, help="Required selected outer folds in EVERY repetition")
    parser.add_argument("--top-n", type=int, default=10, help="Displayed rows per trial; full results are always exported")
    parser.add_argument("--save-bootstrap", action="store_true", help="Save aggregate bootstrap effect/share arrays")
    args = parser.parse_args()
    run(args.input, args.output, args.bootstrap, args.min_folds, args.top_n, args.save_bootstrap)


if __name__ == "__main__":
    main()
